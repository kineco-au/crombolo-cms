/**
 * Story 306: every bundle says whether it is a site package or an extension;
 * the hash covers what it says; each way in takes only its own kind; and a
 * site package's check opens with what it replaces.
 */
import { afterEach, describe, expect, test } from 'bun:test'
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import {
  discoverBundles,
  SITE_PACKAGE_NOT_INSTALLED,
  UNTYPED_BUNDLE,
  validateBundlePackage,
} from '@crombolo/backoffice-host'
import { carriedSections, readBundle, sitePackageChanges, VERSION } from '@crombolo/server'
import {
  BUNDLE_FORMAT_VERSION,
  type BundleFile,
  type BundlePackageInfo,
  type BundleType,
  type ContentSet,
  loadBundle,
  OLDEST_BUNDLE_FORMAT_VERSION,
  writeBundle,
  writeBundlePackage,
} from '@crombolo/transfer'
import { bundleFormatProblem } from '../packages/cli/src/remote/client.ts'
import { siteDeclaring } from './support/bundles.ts'

const dirs: string[] = []
afterEach(() => {
  while (dirs.length > 0) rmSync(dirs.pop() as string, { recursive: true, force: true })
})

const temp = (name: string) => {
  mkdirSync(join(process.cwd(), 'output'), { recursive: true })
  const dir = mkdtempSync(join(process.cwd(), 'output', `${name}-`))
  dirs.push(dir)
  return dir
}

const SET: ContentSet = {
  manifest: {
    formatVersion: BUNDLE_FORMAT_VERSION,
    id: 'site-packages',
    createdAt: '2026-11-09T00:00:00.000Z',
    createdBy: 'test',
    integrity: '',
    snapshot: 'published',
    provenance: { siteName: 'Test', schemaVersion: '1.0.0', schemaRevision: '0', schemaHash: null },
    selector: { roots: [], descendants: false, asGiven: [] },
    counts: {},
    dependencies: {
      carried: [],
      expected: [],
      schema: { contentTypes: [], components: [], languages: [] },
    },
    blobs: [],
  },
  nodes: [],
}

const info = (bundleType: BundleType): BundlePackageInfo => ({
  name: `acme-${bundleType}`,
  version: '1.0.0',
  id: `acme-${bundleType}`,
  label: 'Acme',
  peerRange: `>=${VERSION}`,
  private: true,
  bundleType,
})

/** A bundle package written to disk, as it would arrive. */
function packageOf(bundleType: BundleType, sections: BundleFile[] = []): string {
  const dir = temp(`package-${bundleType}`)
  for (const file of writeBundlePackage(writeBundle(SET, undefined, sections), info(bundleType))) {
    mkdirSync(join(dir, file.path, '..'), { recursive: true })
    writeFileSync(join(dir, file.path), file.bytes ?? (file.text as string))
  }
  return dir
}

const messages = (dir: string) => loadBundle(dir).problems.map((problem) => problem.message)

const editJson = (file: string, change: (json: Record<string, unknown>) => void) => {
  const json = JSON.parse(readFileSync(file, 'utf8')) as Record<string, unknown>
  change(json)
  writeFileSync(file, JSON.stringify(json, null, 2))
}

describe('what a bundle says it is', () => {
  test('a site package says so in both files, and reads back as one', () => {
    const dir = packageOf('site')
    expect(messages(dir)).toEqual([])
    expect(loadBundle(dir).set?.manifest.bundleType).toBe('site')
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'))
    expect(pkg.crombolo.bundleType).toBe('site')
    expect(pkg.private).toBe(true)
  })

  test('one with no bundleType, or an unknown one, is refused, saying what to add', () => {
    const dir = packageOf('site')
    editJson(join(dir, 'bundle.json'), (json) => {
      delete json.bundleType
    })
    expect(messages(dir).join()).toContain('it needs `bundleType`')
    editJson(join(dir, 'bundle.json'), (json) => {
      json.bundleType = 'theme'
    })
    expect(messages(dir).join()).toContain('it needs `bundleType`')
  })

  test('changing what it says, in either file, fails the hash', () => {
    const dir = packageOf('site')
    editJson(join(dir, 'bundle.json'), (json) => {
      json.bundleType = 'extension'
    })
    expect(messages(dir).join()).toContain('integrity does not match')
    const other = packageOf('extension')
    editJson(join(other, 'package.json'), (json) => {
      ;(json.crombolo as Record<string, unknown>).bundleType = 'site'
    })
    const said = messages(other).join()
    expect(said).toContain('integrity does not match')
    expect(said).toContain('says it is a site bundle')
  })

  test('an empty hash is refused, not skipped', () => {
    const dir = packageOf('extension')
    editJson(join(dir, 'bundle.json'), (json) => {
      json.integrity = ''
    })
    expect(messages(dir).join()).toContain('has no integrity hash')
  })

  test('an extension never carries the site’s code', () => {
    const dir = packageOf('extension', [{ path: 'code/crombolo.config.ts', text: 'export {}\n' }])
    expect(messages(dir).join()).toContain('never carries the site’s code'.replace('’', "'"))
  })

  test('the oldest format read is the one that says what it is', () => {
    expect(OLDEST_BUNDLE_FORMAT_VERSION).toBe(BUNDLE_FORMAT_VERSION)
  })
})

describe('a site package’s manifest', () => {
  const valid = {
    name: 'acme-site',
    version: '1.0.0',
    private: true,
    peerDependencies: { '@crombolo/crombolo': `>=${VERSION}` },
    crombolo: { bundleType: 'site', id: 'acme-site', content: true },
  }

  test('is private, and declares nothing an extension does', () => {
    expect(validateBundlePackage(valid)).toEqual([])
    expect(validateBundlePackage({ ...valid, private: false }).join()).toContain('"private": true')
    expect(
      validateBundlePackage({ ...valid, crombolo: { ...valid.crombolo, server: 'x' } }).join(),
    ).toContain('declares no "crombolo.server"')
  })

  test('a package that says nothing is refused', () => {
    expect(
      validateBundlePackage({ ...valid, crombolo: { id: 'acme-site', content: true } }),
    ).toContain(UNTYPED_BUNDLE)
  })
})

describe('the way in for each kind', () => {
  test('a site package is never a dependency, and an untyped one is turned off', () => {
    const root = siteDeclaring('site-packages-deps', {
      '@acme/whole-site': {
        json: { private: true, crombolo: { bundleType: 'site', id: 'whole-site', content: true } },
        files: { 'bundle.json': '{}' },
      },
      '@acme/old': {
        json: {
          crombolo: {
            bundleType: undefined,
            id: 'old',
            extensions: [{ type: 'dashboard', alias: 'old.d', name: 'Old', element: 'd.js' }],
          },
        },
      },
    })
    const found = discoverBundles(root)
    expect(found.bundles).toEqual([])
    const byName = new Map(found.problems.map((problem) => [problem.packageName, problem]))
    expect(byName.get('@acme/whole-site')?.problems).toEqual([SITE_PACKAGE_NOT_INSTALLED])
    expect(byName.get('@acme/old')?.untyped).toEqual({ id: 'old' })
  })

  test('applying takes only a site package, and installing only an extension', () => {
    const site = packageOf('site')
    const extension = packageOf('extension')
    expect(() => readBundle(extension, site, undefined, { expects: 'site' })).toThrow(
      'install it with `crombolo bundle install`',
    )
    expect(() => readBundle(site, site, undefined, { expects: 'extension' })).toThrow(
      'apply it with `crombolo site apply`',
    )
    expect(readBundle(site, site, undefined, { expects: 'site' }).set.manifest.bundleType).toBe(
      'site',
    )
  })
})

describe('a site package’s check', () => {
  test('says what it does to the config, package.json and dependencies', () => {
    const siteDir = temp('site-packages-here')
    writeFileSync(
      join(siteDir, 'package.json'),
      JSON.stringify({ dependencies: { kept: '^1', moved: '^1', gone: '^1' } }),
    )
    writeFileSync(join(siteDir, 'crombolo.config.ts'), 'export default {}\n')
    const dir = packageOf('site', [
      {
        path: 'code/package.json',
        text: JSON.stringify({ dependencies: { kept: '^1', moved: '^2', added: '^1' } }),
      },
      { path: 'code/crombolo.config.ts', text: 'export default { siteName: "Elsewhere" }\n' },
    ])
    const changes = sitePackageChanges(
      { siteDir } as never,
      carriedSections(loadBundle(dir) as never),
    )
    expect(changes).toEqual({
      config: 'overwrite',
      packageJson: 'overwrite',
      dependencies: { added: ['added'], removed: ['gone'], changed: ['moved'] },
    })
  })
})

describe('versions across a remote', () => {
  test('a remote that reads this format is fine, either way', () => {
    const formats: [number, number] = [OLDEST_BUNDLE_FORMAT_VERSION, BUNDLE_FORMAT_VERSION]
    expect(bundleFormatProblem({ name: 'live', bundleFormats: formats }, 'send')).toBeUndefined()
    expect(bundleFormatProblem({ name: 'live', bundleFormats: formats }, 'receive')).toBeUndefined()
  })

  test('an older one, or one that names none, says which side to upgrade', () => {
    const older: [number, number] = [BUNDLE_FORMAT_VERSION - 1, BUNDLE_FORMAT_VERSION - 1]
    expect(bundleFormatProblem({ name: 'live', bundleFormats: older }, 'send')).toContain(
      'upgrade the remote first',
    )
    expect(bundleFormatProblem({ name: 'live' }, 'receive')).toContain(
      'a release from before site packages',
    )
    const newer: [number, number] = [BUNDLE_FORMAT_VERSION + 1, BUNDLE_FORMAT_VERSION + 1]
    expect(bundleFormatProblem({ name: 'live', bundleFormats: newer }, 'send')).toContain(
      'upgrade this crombolo first',
    )
  })
})
