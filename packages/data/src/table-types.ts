/**
 * Writes the types of crombolo's own tables from a migrated SQLite and Postgres
 * database (story 221), so queries are checked against both engines at once.
 * `bun run db:types` writes them; a dialect-suite test fails when they drift.
 */
import type { Db } from './database.ts'

interface Column {
  name: string
  /** The Postgres type name (`int4`, `timestamptz`), or SQLite's declared type, lower case. */
  type: string
  nullable: boolean
  generated: boolean
}

type Tables = Map<string, Map<string, Column>>

const FTS_SHADOW = /_(data|idx|content|docsize|config)$/

async function sqliteTables(db: Db): Promise<Tables> {
  const masters = await db.query<{ name: string; sql: string | null }>(
    "SELECT name, sql FROM sqlite_master WHERE type = 'table' AND name NOT LIKE 'sqlite_%'",
  )
  const virtual = masters
    .filter((m) => /^\s*create\s+virtual/i.test(m.sql ?? ''))
    .map((m) => m.name)
  const tables: Tables = new Map()
  for (const { name } of masters) {
    if (virtual.includes(name)) continue
    if (virtual.some((v) => name.startsWith(`${v}_`) && FTS_SHADOW.test(name))) continue
    const info = await db.query<{
      name: string
      type: string
      notnull: number
      dflt_value: string | null
      pk: number
    }>(`PRAGMA table_info("${name}")`)
    const columns = new Map<string, Column>()
    for (const c of info) {
      // An INTEGER PRIMARY KEY is the rowid, which SQLite assigns.
      const rowid = c.pk === 1 && c.type.toUpperCase() === 'INTEGER'
      columns.set(c.name, {
        name: c.name,
        type: c.type.toLowerCase(),
        nullable: c.notnull === 0 && c.pk === 0,
        generated: c.dflt_value !== null || rowid,
      })
    }
    tables.set(name, columns)
  }
  return tables
}

async function postgresTables(db: Db): Promise<Tables> {
  const rows = await db.query<{
    table_name: string
    column_name: string
    udt_name: string
    is_nullable: string
    column_default: string | null
    is_identity: string
  }>(
    `SELECT c.table_name, c.column_name, c.udt_name, c.is_nullable, c.column_default, c.is_identity
       FROM information_schema.columns c
       JOIN information_schema.tables t
         ON t.table_schema = c.table_schema AND t.table_name = c.table_name
      WHERE c.table_schema = current_schema() AND t.table_type = 'BASE TABLE'`,
  )
  const tables: Tables = new Map()
  for (const r of rows) {
    let columns = tables.get(r.table_name)
    if (!columns) {
      columns = new Map()
      tables.set(r.table_name, columns)
    }
    columns.set(r.column_name, {
      name: r.column_name,
      type: r.udt_name.toLowerCase(),
      nullable: r.is_nullable === 'YES',
      generated: r.column_default !== null || r.is_identity === 'YES',
    })
  }
  return tables
}

/** The TypeScript type of a column, named by an alias declared in the generated file. */
function typeOf(type: string): string {
  if (/^(int2|int4|integer|smallint)$/.test(type)) return 'number'
  if (type === 'int8' || type === 'bigint') return 'BigInteger'
  if (type === 'bool' || type === 'boolean') return 'Bool'
  if (/^timestamp/.test(type)) return 'Timestamp'
  if (type === 'numeric') return 'Decimal'
  if (/^(float4|float8|real|double)/.test(type)) return 'number'
  if (type === 'bytea' || type === 'blob') return 'Bytes'
  if (type === 'tsvector') return 'unknown'
  return 'string'
}

/** Postgres knows more than SQLite's declared types do, so its type leads where both have one. */
function merge(sqlite: Column | undefined, postgres: Column | undefined): Column {
  const lead = (postgres ?? sqlite) as Column
  return {
    name: lead.name,
    type: lead.type,
    nullable: (sqlite?.nullable ?? false) || (postgres?.nullable ?? false),
    generated: (sqlite?.generated ?? false) || (postgres?.generated ?? false),
  }
}

const IDENTIFIER = /^[A-Za-z_$][A-Za-z0-9_$]*$/
const key = (name: string) => (IDENTIFIER.test(name) ? name : `'${name}'`)

const PREAMBLE = `// Generated by \`bun run db:types\` from freshly migrated SQLite and Postgres
// databases (story 221). Do not edit: add a migration and regenerate.
import type { ColumnType, Generated } from 'kysely'

/** SQLite answers 0 or 1; write \`dialect.boolValue(…)\`, read through \`fromDbBool\`. */
type Bool = ColumnType<boolean | number, boolean | number, boolean | number>
/** Postgres answers a Date, SQLite an ISO string; write \`DbDate.toDb\`, read through \`DbDate.fromDb\`. */
type Timestamp = ColumnType<Date | string, string, string>
type Decimal = ColumnType<string | number, string | number, string | number>
type BigInteger = ColumnType<number | string | bigint, number | bigint, number | bigint>
type Bytes = Uint8Array
/** A column with a default, so an insert may leave it out, whatever its read and write types. */
type Default<C> = C extends ColumnType<infer S, infer I, infer U>
  ? ColumnType<S, I | undefined, U>
  : Generated<C>
`

/** The generated file's text for the two migrated databases. */
export async function tableTypes(sqlite: Db, postgres: Db): Promise<string> {
  const [lite, pg] = await Promise.all([sqliteTables(sqlite), postgresTables(postgres)])
  const names = [...new Set([...lite.keys(), ...pg.keys()])].sort()
  const out = [PREAMBLE, 'export interface CoreTables {']
  for (const table of names) {
    const a = lite.get(table)
    const b = pg.get(table)
    const only = !a ? ' // Postgres only' : !b ? ' // SQLite only' : ''
    out.push(`  ${key(table)}: {${only}`)
    const columns = [...new Set([...(a?.keys() ?? []), ...(b?.keys() ?? [])])].sort()
    for (const name of columns) {
      const c = merge(a?.get(name), b?.get(name))
      let t = typeOf(c.type)
      if (c.nullable) t = `${t} | null`
      if (c.generated) t = t === 'number' || t === 'string' ? `Generated<${t}>` : `Default<${t}>`
      out.push(`    ${key(name)}: ${t}`)
    }
    out.push('  }')
  }
  out.push('}', '')
  return out.join('\n')
}
