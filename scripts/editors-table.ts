/**
 * Writes `packages/schema/src/editors.gen.ts` from the vendored back office's
 * manifests (story 357): each property editor schema and each editor UI the data
 * type editor offers, with their settings and the values it fills in for a new
 * data type.
 *
 *   bun run editors:table           write it
 *   bun run editors:table --check   fail when it differs from the manifests
 *
 * The manifests are imported with every other module of the client stubbed, so
 * nothing that needs a browser runs.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { Glob } from 'bun'

const ROOT = join(import.meta.dir, '..')
const PACKAGES = join(ROOT, 'packages/backoffice-dist/dist/packages')
export const EDITORS_TABLE = join(ROOT, 'packages/schema/src/editors.gen.ts')

const MANIFEST_MODULE = /(\/manifests?\.js|\/constants\.js|\/Umbraco\.[^/]+\.js)$/
const DECLARES_EDITOR = /type:\s*['"]propertyEditor(Schema|Ui)['"]/

interface Manifest {
  type: string
  alias: string
  name?: string
  meta?: {
    label?: string
    propertyEditorSchemaAlias?: string
    defaultPropertyEditorUiAlias?: string
    settings?: {
      properties?: Array<{ alias: string; propertyEditorUiAlias: string }>
      defaultData?: Array<{ alias: string; value: unknown }>
    }
  }
}

function stubTheRest() {
  const transpiler = new Bun.Transpiler({ loader: 'js' })
  Bun.plugin({
    name: 'editor-manifests',
    setup(build) {
      build.onLoad({ filter: /backoffice-dist\/dist\/packages\/.*\.js$/ }, ({ path }) => {
        const text = readFileSync(path, 'utf8')
        if (MANIFEST_MODULE.test(path)) return { contents: text, loader: 'js' }
        const { exports } = transpiler.scan(text)
        return {
          contents: exports
            .map((name) =>
              name === 'default' ? 'export default undefined' : `export const ${name} = undefined`,
            )
            .join('\n'),
          loader: 'js',
        }
      })
    },
  })
}

const sorted = <T>(record: Record<string, T>): Record<string, T> =>
  Object.fromEntries(Object.entries(record).sort(([a], [b]) => a.localeCompare(b)))

const settingsOf = (manifest: Manifest | undefined) =>
  sorted(
    Object.fromEntries(
      (manifest?.meta?.settings?.properties ?? []).map((p) => [p.alias, p.propertyEditorUiAlias]),
    ),
  )
const defaultsOf = (manifest: Manifest | undefined) =>
  sorted(
    Object.fromEntries(
      (manifest?.meta?.settings?.defaultData ?? []).map((d) => [d.alias, d.value]),
    ),
  )

/** The table's source text, from the manifests as they are now. */
export async function editorsTable(): Promise<string> {
  stubTheRest()
  const schemas = new Map<string, Manifest>()
  const uis = new Map<string, Manifest>()
  const visit = (value: unknown) => {
    if (Array.isArray(value)) value.forEach(visit)
    else if (value && typeof value === 'object' && typeof (value as Manifest).type === 'string') {
      const manifest = value as Manifest
      if (manifest.type === 'propertyEditorSchema') schemas.set(manifest.alias, manifest)
      if (manifest.type === 'propertyEditorUi' && manifest.meta?.propertyEditorSchemaAlias)
        uis.set(manifest.alias, manifest)
    }
  }
  const files = [...new Glob('**/*.js').scanSync(PACKAGES)].sort()
  for (const file of files) {
    const path = join(PACKAGES, file)
    if (!DECLARES_EDITOR.test(readFileSync(path, 'utf8'))) continue
    Object.values(await import(path)).forEach(visit)
  }
  if (uis.size === 0) throw new Error(`no editor manifests under ${PACKAGES}`)
  const schemaTable = sorted(
    Object.fromEntries(
      [...schemas].map(([alias, m]) => [
        alias,
        {
          name: m.name ?? alias,
          defaultUi: m.meta?.defaultPropertyEditorUiAlias ?? null,
          settings: settingsOf(m),
          defaultData: defaultsOf(m),
        },
      ]),
    ),
  )
  const uiTable = sorted(
    Object.fromEntries(
      [...uis].map(([alias, m]) => [
        alias,
        {
          label: m.meta?.label ?? alias,
          schema: m.meta?.propertyEditorSchemaAlias as string,
          settings: settingsOf(m),
          defaultData: defaultsOf(m),
        },
      ]),
    ),
  )
  return [
    '// Generated by `bun run editors:table` from the vendored back office. Do not edit.',
    "import type { EditorSchemaEntry, EditorUiEntry } from './editors.ts'",
    '',
    '/** Each property editor schema: its default editor UI, its settings and their defaults. */',
    `export const EDITOR_SCHEMAS: Readonly<Record<string, EditorSchemaEntry>> = ${JSON.stringify(schemaTable, null, 2)}`,
    '',
    '/** Each editor UI the data type editor offers: its schema, label, settings and defaults. */',
    `export const EDITOR_UIS: Readonly<Record<string, EditorUiEntry>> = ${JSON.stringify(uiTable, null, 2)}`,
    '',
  ].join('\n')
}

if (import.meta.main) {
  const text = await editorsTable()
  if (process.argv.includes('--check')) {
    if (readFileSync(EDITORS_TABLE, 'utf8') !== text) {
      console.error(
        'packages/schema/src/editors.gen.ts differs from the vendored manifests: run `bun run editors:table`',
      )
      process.exit(1)
    }
    console.log('the editor table matches the vendored manifests')
  } else {
    writeFileSync(EDITORS_TABLE, text)
    console.log(`wrote ${EDITORS_TABLE}`)
  }
}
